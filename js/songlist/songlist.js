// =====================
// STATE
// =====================

let currentSort = { type: "date", order: "desc" };

// =====================
// DOM REFERENCES
// =====================

const songlistEl = document.querySelector(".songlist");
const sortButtons = document.querySelectorAll("#sortDate, #sortBPM, #sortKey");
const filterCheckboxes = document.querySelectorAll(".typeFilter");

// =====================
// HELPERS
// =====================

function getActiveTypes() {
  return Array.from(filterCheckboxes)
    .filter(cb => cb.checked)
    .map(cb => cb.value);
}

function parseDate(dateStr) {
  return new Date(dateStr.split(".").reverse().join("-"));
}

function getPrimaryBPM(song) {
  return typeof song.bpm?.[0] === "number" ? song.bpm[0] : null;
}

function getUniqueSongs(releases) {
  const allSongs = releases.flatMap(r => r.songs);
  return allSongs.filter((song, index, self) =>
    index === self.findIndex(s =>
      s.title === song.title &&
      s.key === song.key &&
      JSON.stringify(s.bpm) === JSON.stringify(song.bpm)
    )
  );
}

function createTrack(song, showTrackNumber = false) {
  const track = document.createElement("div");
  track.classList.add("track");

  track.innerHTML = `
    ${showTrackNumber ? `<div class="trackInfoText trackNumber">${song.track ?? ""}</div>` : ""}
    <div class="trackInfoText trackTitle">${song.title}</div>
    <div class="trackInfoText trackBPM">
      ${song.bpm?.[0] ?? "No BPM"}${song.bpm?.[1] ? " / " + song.bpm[1] : ""} BPM
    </div>
    <div class="trackInfoText trackKey">${song.key}</div>
  `;

  return track;
}

function createReleaseBlock(release) {
  const block = document.createElement("div");
  block.classList.add("release");

  const title = document.createElement("div");
  title.classList.add("releaseTitle");
  title.innerHTML = `
    <span class="releaseDate">${release.releaseDate}</span>
    ${release.title}
    <span class="releaseType">${release.type}</span>
  `;

  block.appendChild(title);

  release.songs.forEach(song => {
    block.appendChild(createTrack(song, true));
  });

  return block;
}

// =====================
// RENDER MODES
// =====================

function renderDateView(releases) {
  releases
    .sort((a, b) => {
      const da = parseDate(a.releaseDate);
      const db = parseDate(b.releaseDate);
      return currentSort.order === "asc" ? da - db : db - da;
    })
    .forEach(release => {
      songlistEl.appendChild(createReleaseBlock(release));
    });
}

function renderBPMView(releases) {
  const songs = getUniqueSongs(releases);

  songs.sort((a, b) => {
    const aBPM = getPrimaryBPM(a) ?? 9999;
    const bBPM = getPrimaryBPM(b) ?? 9999;
    return currentSort.order === "asc" ? aBPM - bBPM : bBPM - aBPM;
  });

  songs.forEach(song => {
    songlistEl.appendChild(createTrack(song));
  });
}

function renderKeyView(releases) {
  const songs = getUniqueSongs(releases);

  songs.sort((a, b) => {
    if (a.key === "No Key") return 1;
    if (b.key === "No Key") return -1;

    const ak = keyOrder[a.key] ?? -1;
    const bk = keyOrder[b.key] ?? -1;
    return currentSort.order === "asc" ? ak - bk : bk - ak;
  });

  songs.forEach(song => {
    songlistEl.appendChild(createTrack(song));
  });
}

// =====================
// MAIN RENDER
// =====================

function renderList() {
  songlistEl.innerHTML = "";

  const activeTypes = getActiveTypes();
  const filtered = releases.filter(r => activeTypes.includes(r.type));

  if (currentSort.type === "bpm") return renderBPMView(filtered);
  if (currentSort.type === "key") return renderKeyView(filtered);

  renderDateView(filtered);
}

// =====================
// EVENTS
// =====================

filterCheckboxes.forEach(cb =>
  cb.addEventListener("change", renderList)
);

sortButtons.forEach(button => {
  button.addEventListener("click", () => {
    sortButtons.forEach(b => {
      b.classList.remove("active");
      b.textContent = b.textContent.replace(/[▲▼]/, "");
    });

    button.classList.add("active");

    const type = button.id.replace("sort", "").toLowerCase();
    button.dataset.order =
      currentSort.type === type && button.dataset.order === "desc"
        ? "asc"
        : "desc";

    currentSort = { type, order: button.dataset.order };

    button.textContent = `${type === "date" ? "Date" : type === "bpm" ? "BPM" : "Key"} ${
      button.dataset.order === "asc" ? "▲" : "▼"
    }`;

    renderList();
  });
});

document.addEventListener("DOMContentLoaded", () => {
  const dateBtn = document.getElementById("sortDate");
  dateBtn.classList.add("active");
  dateBtn.dataset.order = "desc";
  dateBtn.textContent = "Date ▼";

  renderList();
});
